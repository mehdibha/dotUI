/**
 * The preset gap ledger, built from every pack's gaps.json
 * (packages/capture/refs/<id>/gaps.json): looks per pattern, the
 * systems that need each, and which meet the proposal bar. Run from www/.
 *
 *   tsx scripts/presets-gaps.ts [--pattern <id>] [--json]
 *     Prints the ledger as Markdown, the pattern counts first.
 *
 *   tsx scripts/presets-gaps.ts --look <id>
 *     Every system's reading of one look, with its stand-in.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs"
import { resolve } from "node:path"
import { parseArgs } from "node:util"

import {
  type GapsFile,
  ledger,
  LOOKS,
  type LookId,
  type Pattern,
  PATTERNS,
} from "@dotui/capture/looks"
import { REFS } from "@dotui/capture/preset-pages"

import { getPreset } from "../src/modules/presets"

const { values: args } = parseArgs({
  options: {
    pattern: { type: "string" },
    look: { type: "string" },
    json: { type: "boolean", default: false },
  },
})

const packs: Record<string, GapsFile> = {}
for (const id of readdirSync(REFS)) {
  const file = resolve(REFS, id, "gaps.json")
  if (!existsSync(file)) continue
  const json = JSON.parse(readFileSync(file, "utf8")) as GapsFile
  const unknown = json.gaps.filter((gap) => !Object.hasOwn(LOOKS, gap.look))
  if (unknown.length) {
    console.error(
      `${file}: unknown looks ${unknown.map((gap) => gap.look).join(", ")} (add them to looks.ts)`,
    )
    process.exit(1)
  }
  packs[id] = json
}

const name = (pack: string) => getPreset(pack)?.name ?? pack

if (args.look) {
  if (!Object.hasOwn(LOOKS, args.look)) {
    console.error(`unknown look "${args.look}"`)
    process.exit(1)
  }
  const id = args.look as LookId
  console.log(`# ${id}: ${LOOKS[id].label}\n`)
  for (const [pack, file] of Object.entries(packs))
    for (const gap of file.gaps.filter((gap) => gap.look === id)) {
      console.log(`## ${name(pack)} (${gap.source})\n\n${gap.title}`)
      if (gap.note) console.log(`\n${gap.note}`)
      if (gap.standin) console.log(`\nStand-in: ${gap.standin}`)
      for (const row of gap.rows ?? [])
        console.log(
          `- ${row.mode} ${row.part} ${row.prop}: ${row.reference} (preset ${row.preset})`,
        )
      console.log("")
    }
  process.exit(0)
}

if (args.pattern && !Object.hasOwn(PATTERNS, args.pattern)) {
  console.error(
    `unknown pattern "${args.pattern}". Patterns: ${Object.keys(PATTERNS).join(", ")}`,
  )
  process.exit(1)
}
const rows = ledger(packs).filter(
  (row) => !args.pattern || row.pattern === args.pattern,
)

if (args.json) {
  console.log(JSON.stringify(rows, null, 2))
  process.exit(0)
}

const entries = Object.values(packs).reduce(
  (sum, file) => sum + file.gaps.length,
  0,
)
console.log(
  `# Preset gap ledger\n\nGenerated by \`pnpm presets:gaps\` from ${Object.keys(packs).length} packs' gaps.json: ${rows.length} looks, ${entries} system entries. The bar: 3 systems, or 2 with a north star (Material 3, Vercel, Linear); color engine looks wait for the engine rewrite.\n`,
)
console.log("| Pattern | Looks | Entries | At the bar |")
console.log("| --- | --- | --- | --- |")
for (const pattern of Object.keys(PATTERNS) as Pattern[]) {
  const looks = rows.filter((row) => row.pattern === pattern)
  if (!looks.length) continue
  const count = looks.reduce((sum, row) => sum + row.systems.length, 0)
  console.log(
    `| ${PATTERNS[pattern].label} | ${looks.length} | ${count} | ${looks.filter((row) => row.bar).length} |`,
  )
}
for (const pattern of Object.keys(PATTERNS) as Pattern[]) {
  const looks = rows.filter((row) => row.pattern === pattern)
  if (!looks.length) continue
  console.log(`\n## ${PATTERNS[pattern].label}\n`)
  console.log("| Look | | Systems | Bar |")
  console.log("| --- | --- | --- | --- |")
  for (const row of looks)
    console.log(
      `| \`${row.look}\` | ${row.label} | ${row.systems.length}: ${row.systems.map(name).join(", ")} | ${row.bar ? "met" : ""} |`,
    )
}
